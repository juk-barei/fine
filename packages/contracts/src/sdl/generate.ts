import { emitWireModules } from './emitter.ts';
import { authWire, rootWire, walletsWire } from './wire.ts';

/**
 * Every served SDL file: which wire module generates it, and where the
 * checked-in artifact lands. The server's `typePaths` glob picks the files
 * up from exactly these paths.
 */
export const SDL_TARGETS = [
  { module: rootWire, target: 'apps/server/src/schema.graphql' },
  { module: authWire, target: 'apps/server/src/modules/auth/auth.graphql' },
  { module: walletsWire, target: 'apps/server/src/modules/wallets/wallets.graphql' },
] as const;

const GENERATED_HEADER = [
  '# Generated by `npm run generate:sdl` in @repo/contracts — do not edit.',
  '# The wire registry in packages/contracts/src/sdl/wire.ts is the source of truth.',
  '',
].join('\n');

/** One generated SDL file: where it lands and its full contents. */
export interface SdlFile {
  /** Repository-relative path of the generated file. */
  target: string;
  /** The file's full contents, generated header included. */
  contents: string;
}

/** Renders every served SDL file from the wire registry, in target order. */
export function renderSdlFiles(): SdlFile[] {
  const emitted = emitWireModules(SDL_TARGETS.map(({ module }) => module));
  return SDL_TARGETS.map(({ target }, index) => ({
    target,
    contents: GENERATED_HEADER + emitted[index].sdl,
  }));
}
